    };
    public static string Rule(string service, string method, object?[] args)
    {

        if (service == "InsuranceManagementService" && method == "ReviewClaimAsync" && args.FirstOrDefault() is RaccoonWarehouse.Domain.Insurance.InsuranceClaimReviewDto review)
            return review.Status == RaccoonWarehouse.Domain.Insurance.InsuranceClaimStatus.Rejected ? "InsuranceClaims.Reject" : "InsuranceClaims.Approve";
        if (service == "ManualInsuranceProvider") return method == "SubmitClaimBatchAsync" ? "InsuranceClaims.Submit" : "InsurancePolicies.View";
        if (service == "PandaOrderSyncService") return "Orders.Import";
        if (service == "AccountingOperationService" && method == "EnqueueInvoiceAsync" && args.OfType<InvoiceWriteDto>().FirstOrDefault() is { } queued)
            return InvoiceResource(queued) + ".Post";
        if (service == "RefundAuthorizationCodeService") return method == "SetCodeAsync" ? "Settings.ManageSettings" : method == "ValidateCodeAsync" ? "SalesInvoice.Return" : "POS.View|Settings.View";
        if (service == "InsuranceManagementService" && method == "SaveInvoiceCoverageAsync") return "InsuranceClaims.Create;SalesInvoice.Post";
        if (service == "InvoiceService" && args.OfType<InvoiceWriteDto>().FirstOrDefault() is { } invoice)
        {
            var resource = InvoiceResource(invoice);
            var action = method == "UpdateAsync" ? "Edit" : "Create";
            var rule = resource + "." + action;
            if (invoice.InvoiceType is InvoiceType.Return or InvoiceType.Exchange) rule += ";SalesInvoice.Return";
            if (invoice.InvoiceType == InvoiceType.PurchaseReturn) rule += ";PurchaseReturn.Confirm";
            if (invoice.Status is not (InvoiceStatus.Draft or InvoiceStatus.OnHold)) rule += ";" + resource + ".Post";
            if (invoice.Status == InvoiceStatus.Cancelled) rule += ";" + resource + ".Cancel";
            return rule;
        }
        if (service == "InsuranceManagementService" && method.StartsWith("Save", StringComparison.Ordinal) && method != "SaveInvoiceCoverageAsync")
        {
            var resource = method switch
            {
                "SaveCompanyAsync" => "InsuranceCompanies", "SavePlanAsync" => "InsuranceNetworks",
                "SaveMemberPolicyAsync" => "InsurancePolicies", _ => "InsuranceContracts"
            };
            var id = args.FirstOrDefault()?.GetType().GetProperty("Id")?.GetValue(args.FirstOrDefault());
            return resource + (id is int value && value > 0 ? ".Edit" : ".Create");
        }
        if (service == "StockService" && method is "GetAllAsync" or "GetAllWithFilteringAndIncludeAsync" or "GetAllWithIncludeAsync")
            return "StockLots.View|Products.View|POS.View|SalesInvoice.View|PurchaseInvoice.View|PurchaseReturn.View|StockInVoucher.View|StockOutVoucher.View|PurchaseOrder.View|PurchaseRequest.View|GoodsReceipt.View|InsuranceContracts.View|InsuranceClaims.View";
        if (Methods.TryGetValue(service + "." + method, out var exact)) return exact;
        if (!Resources.TryGetValue(service, out var resourceName)) return "Permissions.Unmapped";
        return resourceName + "." + (method switch
        {
            "CreateAsync" => "Create", "UpdateAsync" => "Edit", "DeleteAsync" or "SoftDeleteAsync" => "Delete",
            "GetByIdAsync" or "GetAllAsync" or "GetAllWithIncludeAsync" or "GetByIdWithIncludeAsync" or
            "GetWriteDtoByIdWithIncludeAsync" or "GetPagedListAsync" or "GetWriteDtoByIdAsync" or
            "GetAllWithFilteringAndIncludeAsync" or "GetAllWriteDtoWithFilteringAndIncludeAsync" or
            "GetAllWithAdvancedIncludeAsync" or "GetReadDtoPagedListAsync" => "View",
            _ => "Unmapped"
        });
    }
