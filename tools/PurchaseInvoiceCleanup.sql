/*
  Run only against db_acff96_pharmacdevelopment after taking a backup.
  Deletes all invoice rows and rows directly generated/referenced by them.
  Preserves users/suppliers, products/product units, warehouses, accounts,
  settings, permissions, and EF migration history.
*/
SET NOCOUNT ON;
SET XACT_ABORT ON;

BEGIN TRANSACTION;

DECLARE @InvoiceIds TABLE (Id int PRIMARY KEY);
DECLARE @InvoiceLineIds TABLE (Id int PRIMARY KEY);
DECLARE @JournalEntryIds TABLE (Id int PRIMARY KEY);
DECLARE @VoucherIds TABLE (Id int PRIMARY KEY);

INSERT INTO @InvoiceIds (Id)
SELECT Id FROM dbo.Invoice;

INSERT INTO @InvoiceLineIds (Id)
SELECT Id FROM dbo.InvoiceLine
WHERE InvoiceId IN (SELECT Id FROM @InvoiceIds);

INSERT INTO @JournalEntryIds (Id)
SELECT Id FROM dbo.JournalEntries
WHERE ReferenceId IN (SELECT Id FROM @InvoiceIds)
   OR SourceId IN (SELECT Id FROM @InvoiceIds);

INSERT INTO @VoucherIds (Id)
SELECT DISTINCT VoucherId FROM dbo.Invoice
WHERE VoucherId IS NOT NULL;

-- Remove dependent accounting and payment rows first.
DELETE FROM dbo.JournalEntryLines
WHERE JournalEntryId IN (SELECT Id FROM @JournalEntryIds)
   OR InvoiceId IN (SELECT Id FROM @InvoiceIds);

DELETE FROM dbo.JournalEntries
WHERE Id IN (SELECT Id FROM @JournalEntryIds);

DELETE FROM dbo.FinancialTransaction
WHERE InvoiceId IN (SELECT Id FROM @InvoiceIds)
   OR SourceId IN (SELECT Id FROM @InvoiceIds);

DELETE FROM dbo.[Check]
WHERE InvoiceId IN (SELECT Id FROM @InvoiceIds)
   OR VoucherId IN (SELECT Id FROM @VoucherIds);

DELETE FROM dbo.InvoicePayments
WHERE InvoiceId IN (SELECT Id FROM @InvoiceIds);

-- Remove stock movements/lots generated by these invoice lines.
DELETE FROM dbo.StockTransaction
WHERE InvoiceId IN (SELECT Id FROM @InvoiceIds)
   OR StockLotId IN (
       SELECT Id FROM dbo.StockLot
       WHERE SourcePurchaseLineId IN (SELECT Id FROM @InvoiceLineIds)
   );

DELETE FROM dbo.StockLot
WHERE SourcePurchaseLineId IN (SELECT Id FROM @InvoiceLineIds);

DELETE FROM dbo.Voucher
WHERE Id IN (SELECT Id FROM @VoucherIds);

DELETE FROM dbo.InvoiceLine
WHERE Id IN (SELECT Id FROM @InvoiceLineIds);

DELETE FROM dbo.Invoice
WHERE Id IN (SELECT Id FROM @InvoiceIds);

COMMIT TRANSACTION;

SELECT
    (SELECT COUNT_BIG(*) FROM dbo.Invoice) AS RemainingInvoices,
    (SELECT COUNT_BIG(*) FROM dbo.InvoiceLine) AS RemainingInvoiceLines,
    (SELECT COUNT_BIG(*) FROM dbo.InvoicePayments) AS RemainingInvoicePayments;
